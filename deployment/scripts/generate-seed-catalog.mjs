#!/usr/bin/env node
/**
 * Generates deployment/docker/seed-catalog.sql with ~200 titles, 10 weeks revenue,
 * and a judge-visible demo story:
 * - Comedy oversupplied / weak WoW
 * - Thriller under-indexed vs revenue share
 * - Cannibal pair: True Crime: Highway 101 + Redux (Documentary, top quartile)
 * - Breakout LATAM: Crimen sin Fronteras: Bogotá (Thriller, es, rising WoW)
 */
import { writeFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '../docker/seed-catalog.sql');

const WEEKS = 10;
const LATEST_WEEK = new Date('2026-08-18');

function weekStart(offsetWeeks) {
  const d = new Date(LATEST_WEEK);
  d.setUTCDate(d.getUTCDate() - offsetWeeks * 7);
  return d.toISOString().slice(0, 10);
}

function esc(s) {
  return s.replace(/'/g, "''");
}

const STORY = {
  breakout: {
    id: 'a1b2c3d4-e5f6-7890-abcd-ef1234567890',
    title: 'Crimen sin Fronteras: Bogotá',
    genre: 'Thriller',
    language: 'es',
    description: 'Thriller LATAM breakout — detective series with surging week-over-week revenue.',
    cast: ['Gael García Bernal', 'Karla Souza'],
    baseRev: 120,
    wowGrowth: 1.35
  },
  cannibalA: {
    id: 'b2c3d4e5-f6a7-8901-bcde-f12345678901',
    title: 'True Crime: Highway 101',
    genre: 'Documentary',
    language: 'en',
    description: 'True-crime doc — cannibalization pair A (top quartile revenue).',
    cast: ['Host'],
    baseRev: 900
  },
  cannibalB: {
    id: 'c3d4e5f6-a7b8-9012-cdef-123456789012',
    title: 'True Crime: Highway 101 Redux',
    genre: 'Documentary',
    language: 'en',
    description: 'Near-duplicate true-crime doc — cannibalization pair B (top quartile).',
    cast: ['Host'],
    baseRev: 880
  }
};

const GENRES = [
  { name: 'Comedy', count: 52, langMix: 0.35, revScale: 0.35, wow: -0.05 },
  { name: 'Drama', count: 32, langMix: 0.4, revScale: 0.55, wow: 0.02 },
  { name: 'Thriller', count: 14, langMix: 0.45, revScale: 1.4, wow: 0.08 },
  { name: 'Documentary', count: 22, langMix: 0.3, revScale: 0.9, wow: 0.03 },
  { name: 'Action', count: 18, langMix: 0.35, revScale: 0.7, wow: 0.01 },
  { name: 'Romance', count: 16, langMix: 0.4, revScale: 0.5, wow: -0.02 },
  { name: 'Horror', count: 14, langMix: 0.25, revScale: 0.65, wow: 0.04 },
  { name: 'Sci-Fi', count: 14, langMix: 0.2, revScale: 0.75, wow: 0.05 },
  { name: 'Animation', count: 10, langMix: 0.35, revScale: 0.45, wow: 0.0 }
];

const comedyPrefixes = ['Laugh', 'Giggle', 'Chuckle', 'Sitcom', 'Prank', 'Roast', 'Banter'];
const dramaPrefixes = ['Broken', 'Silent', 'Fading', 'Winter', 'Harbor', 'Letters'];
const filler = ['Night', 'Dream', 'City', 'Road', 'Echo', 'Line', 'Hour'];

function syntheticTitle(genre, i) {
  const pools = {
    Comedy: comedyPrefixes,
    Drama: dramaPrefixes,
    Thriller: ['Shadow', 'Protocol', 'Cipher', 'Veil', 'Crossing'],
    Documentary: ['Lens on', 'Archive:', 'Chronicle of', 'Field Notes:'],
    Action: ['Strike', 'Velocity', 'Burnout', 'Drift'],
    Romance: ['Hearts', 'Sunset', 'Promise', 'Always'],
    Horror: ['Whisper', 'Crawl', 'Hollow', 'Blackout'],
    'Sci-Fi': ['Orbit', 'Signal', 'Nexus', 'Quantum'],
    Animation: ['Pixel', 'Spark', 'Wonder', 'Tiny']
  };
  const p = pools[genre] ?? ['Title'];
  const a = p[i % p.length];
  const b = filler[(i * 3) % filler.length];
  return `${a} ${b} ${i + 1}`;
}

const titles = [];
const usedStoryIds = new Set(Object.values(STORY).map(s => s.id));

for (const [key, s] of Object.entries(STORY)) {
  titles.push({ ...s, story: key });
}

let idx = 0;
for (const g of GENRES) {
  for (let i = 0; i < g.count; i++) {
    const title = syntheticTitle(g.name, idx++);
    const language = Math.random() < g.langMix ? 'es' : 'en';
    if (g.name === 'Documentary' && (title.includes('Highway') || i < 2)) continue;
    titles.push({
      id: randomUUID(),
      title,
      genre: g.name,
      language,
      description: `${g.name} catalog title for demo seed.`,
      cast: ['Actor A', 'Actor B'],
      baseRev: 80 + Math.random() * 200 * g.revScale,
      wow: g.wow + (Math.random() - 0.5) * 0.08,
      story: null
    });
  }
}

while (titles.length < 200) {
  titles.push({
    id: randomUUID(),
    title: `Catalog Extra ${titles.length}`,
    genre: 'Drama',
    language: titles.length % 2 ? 'es' : 'en',
    description: 'Padding title for 200+ catalog size.',
    cast: ['Actor'],
    baseRev: 100,
    wow: 0,
    story: null
  });
}

const lines = [
  '-- Auto-generated by deployment/scripts/generate-seed-catalog.mjs',
  '-- Demo story: Comedy oversupplied | Thriller gap | Highway 101 cannibal pair | Bogotá breakout',
  'TRUNCATE TABLE IF EXISTS media_catalog.title_revenue;',
  'TRUNCATE TABLE IF EXISTS media_catalog.media_content;',
  ''
];

for (const t of titles.slice(0, 210)) {
  const cast = `['${t.cast.map(c => esc(c)).join("', '")}']`;
  lines.push(
    `INSERT INTO media_catalog.media_content (id, title, description, genre, release_date, cast, enrichment, language) VALUES ('${t.id}', '${esc(t.title)}', '${esc(t.description)}', '${t.genre}', '2020-01-15', ${cast}, '', '${t.language}');`
  );

  for (let w = WEEKS - 1; w >= 0; w--) {
    const ws = weekStart(w);
    let rev;
    let views;

    if (t.story === 'breakout') {
      const weekFactor = Math.pow(STORY.breakout.wowGrowth, WEEKS - 1 - w);
      rev = STORY.breakout.baseRev * weekFactor * (0.9 + Math.random() * 0.2);
      views = Math.round(rev * 180 + Math.random() * 5000);
    } else if (t.story === 'cannibalA' || t.story === 'cannibalB') {
      rev = t.baseRev + (WEEKS - 1 - w) * 15 + Math.random() * 40;
      views = Math.round(rev * 95);
    } else if (t.genre === 'Comedy') {
      rev = t.baseRev * (0.95 + Math.random() * 0.1);
      views = Math.round(rev * 120);
    } else {
      const drift = 1 + (t.wow ?? 0) * (WEEKS - 1 - w) * 0.15;
      rev = t.baseRev * drift * (0.85 + Math.random() * 0.3);
      views = Math.round(rev * (100 + Math.random() * 80));
    }

    lines.push(
      `INSERT INTO media_catalog.title_revenue (title_id, title, week_start, views, revenue_usd) VALUES ('${t.id}', '${esc(t.title)}', '${ws}', ${views}, ${rev.toFixed(2)});`
    );
  }
}

writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`Wrote ${titles.length} titles to ${OUT}`);
